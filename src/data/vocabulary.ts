/**
 * Deterministically generates today's 30 words based on date seed
 */
export function getDailyWordsForDate(dateStr: string): WordItem[] {
  // Simple seed hash from date string like "2026-10-05"
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const seed = Math.abs(hash);

  // Deterministic shuffle of VOCABULARY_BANK
  const shuffled = [...VOCABULARY_BANK];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(((seed * (i + 1) * 9301 + 49297) % 233280) / 233280 * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  // Exactly 30 words as required
  return shuffled.slice(0, 30);
}

